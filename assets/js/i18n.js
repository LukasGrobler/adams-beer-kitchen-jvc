/* The booking form on ar.html / ru.html: the guest fills it in their language,
   the WhatsApp message greets the team in that language, then gives the details in English. */
(function () {
  function pad(n) { return (n < 10 ? "0" : "") + n; }
  function init() {
    var lang = document.documentElement.getAttribute("lang"), T = window.ABK_I18N[lang], D = window.ABK_DATA;
    if (!T) return;
    /* "Ask Adam in Arabic / Russian": shown once the real AI is switched on */
    var band = document.querySelector("[data-ai-band]");
    if (band && ((D.ai && D.ai.endpoint) || D.api)) {
      band.hidden = false;
      band.querySelector("[data-open-adam]").addEventListener("click", function () { var l = document.querySelector(".bt-launch"); if (l) l.click(); });
    }
    var f = document.querySelector("[data-book-tx]");
    if (!f) return;
    var date = f.querySelector("[name=date]"), time = f.querySelector("[name=time]");
    var now = new Date(Date.now() + (240 + new Date().getTimezoneOffset()) * 60000); /* Dubai time */
    if (now.getHours() < 3) now.setDate(now.getDate() - 1); /* before 3AM it's still last night */
    var today = now.getFullYear() + "-" + pad(now.getMonth() + 1) + "-" + pad(now.getDate());
    date.min = today; date.value = today;
    function label(m) {
      var h = Math.floor(m / 60) % 24, mm = m % 60;
      if (lang === "ru") return pad(h) + ":" + pad(mm);
      var w = h === 0 ? "منتصف الليل" : h < 5 ? "فجرًا" : h < 12 ? "صباحًا" : h === 12 ? "ظهرًا" : "مساءً";
      return (h % 12 || 12) + (mm ? ":" + pad(mm) : "") + " " + w;
    }
    function en(m) { var h = Math.floor(m / 60) % 24; return (h % 12 || 12) + (m % 60 ? ":" + pad(m % 60) : "") + (h < 12 ? "AM" : "PM"); }
    var opts = "";
    for (var m = 12 * 60; m <= 26 * 60; m += 30) opts += '<option value="' + m + '">' + label(m) + "</option>";
    time.innerHTML = opts; time.value = String(19 * 60);
    f.addEventListener("submit", function (e) {
      e.preventDefault();
      var p = (date.value || today).split("-"), d = new Date(+p[0], +p[1] - 1, +p[2]);
      var day = d.toLocaleDateString("en-GB", { weekday: "long", day: "numeric", month: "long" });
      var notes = f.querySelector("[name=notes]").value.trim(), name = f.querySelector("[name=name]").value.trim();
      var lines = [T.waHello.trim(), "", "Hi Adam's Beer Kitchen! I'd like to book a table.", "",
        "Name: " + (name || "…"), "Date: " + day, "Time: " + en(+time.value), "Guests: " + (f.querySelector("[name=guests]").value || 2)];
      if (notes) lines.push("Notes: " + notes);
      lines.push("", T.adam.pageNote);
      window.open("https://wa.me/" + D.venue.whatsapp + "?text=" + encodeURIComponent(lines.join("\n")), "_blank", "noopener");
    });
  }
  if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", init); else init();
})();
